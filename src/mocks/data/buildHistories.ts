export function getSnapshotsByRequirement(requirementId: string) {
  return requirementBuildSnapshots
    .filter((s) => s.requirementId === requirementId)
    .sort((a, b) => a.buildNumber - b.buildNumber)
}

export function getSnapshotsByBuild(buildNumber: number) {
  return requirementBuildSnapshots.filter((s) => s.buildNumber === buildNumber)
}
